"""AurelFlow runtime foundation (P3-FLOW-A).

Local, deterministic workflow orchestration substrate:
graph -> run -> lifecycle state -> ready queue -> scheduler decision.

Hard boundary: AurelFlow orchestrates; the scheduler decides readiness;
nothing in this package executes tools, commands, subprocesses, network
calls, sandbox actions, workers, or business actions. Execution belongs to
P4 AurelExec. Trace verification belongs to P5 AurelTrace.
"""

