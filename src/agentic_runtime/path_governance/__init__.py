"""Path Governance & Source Trust Foundation (P1.7.0).

Foundation-only package: labels, posture vocabulary, closed-world validation,
deterministic serialization, and honest capability reporting.
P1.7.1 adds deterministic path identity schema objects without enforcement.
P1.7.2 adds deterministic source identity schema objects without trust resolution.
P1.7.3 adds deterministic source trust label taxonomy objects without resolver behavior.
P1.7.4 adds deterministic trusted root registry seed objects without authority resolution.
P1.7.5 adds deterministic path normalization and shadow escape candidate detection.
P1.7.6 adds deterministic path authority scope declaration objects without resolver behavior.
P1.7.7 adds deterministic untrusted content boundary declaration objects without filtering or enforcement.
P1.7.8 adds deterministic source provenance and evidence binding seed objects without truth verification or trace/Ledger writes.
P1.7.9 adds deterministic path/source risk classification model objects without resolver or enforcement behavior.
P1.7.10 adds deterministic path governance resolver v0 shadow recommendations without enforcement behavior.
P1.7.11 adds deterministic source trust resolver v0 shadow recommendations without trust mutation.
P1.7.12 adds deterministic path/source conflict and precedence shadow rules without enforcement.
P1.7.13 adds deterministic path resolution trace hook payload model without Ledger write or enforcement.

Architectural law:
  - Projection source labels describe operator-visible truth.
  - Source trust labels describe content origin/trust — a separate axis.
  - P1.7.0 does not resolve paths, enforce governance, bind CLI, or write Ledger.
"""
